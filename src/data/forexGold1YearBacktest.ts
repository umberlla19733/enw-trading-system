// Calculation utility for Forex Standard Lot Sizing
export function calculateForexTradeMetrics(
  trade: (typeof FOREX_GOLD_1YEAR_RAW_TRADES)[0],
  lotSize: number
): BacktestTrade {
  // In XAU/USD Forex:
  // 1 Standard Lot = 100 Troy Ounces
  // Profit = pricePoints * 100 * lotSize
  // Commission = $5 per lot round turn
  const grossPnl = trade.pricePoints * 100 * lotSize;
  const commission = 5 * lotSize;
  const pnlDollar = trade.result === 'BE' ? 0 : Math.round((grossPnl - commission) * 100) / 100;
  
  return {
    id: trade.id,
    direction: trade.direction,
    entryTime: trade.entryTime,
    entryPrice: trade.entryPrice,
    exitTime: trade.exitTime,
    exitPrice: trade.exitPrice,
    sl: trade.sl,
    tp1: trade.tp1,
    tp2: trade.tp2,
    tp: trade.tp2,
    pnlDollar,
    pnlPercent: Math.round((trade.pricePoints / trade.entryPrice) * 100 * 100) / 100,
    result: trade.result,
    exitReason: trade.exitReason,
    setupType: trade.setupType,
    setup: trade.setupType,
    durationMinutes: trade.durationMinutes,
    bars: trade.bars
  };
}

